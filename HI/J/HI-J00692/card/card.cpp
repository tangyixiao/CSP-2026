#include<bits/stdc++.h>
using namespace std;
int n,cyy,a[100100];
int main()
{
	
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	
	scanf("%d%d",&n,&cyy);
	for(int i=1;i<=n;i++)
	{
		scanf("%d",&a[i]);
	}
	for(int i=1;i<=cyy;i++)
	{
		cout<<"0 ";
	}
	return 0;
	
	fclose(stdin);
	fclose(stdout);
	
}
