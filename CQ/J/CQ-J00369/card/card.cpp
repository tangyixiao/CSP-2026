#include <bits/stdc++.h>
using namespace std;
int n,m,a[500010],ans[300010],use[300010];
stack<int> s;
int main(){
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	cin>>n>>m;
	for(int i=1;i<=n;i++) cin>>a[i];
	for(int i=1;i<=n;i++){
		for(int j=i;j<=n;j++){
			if(use[a[j]]){
				while(!s.empty()){
					if(s.top()==a[j]) break;
					use[s.top()]--,s.pop();
				}
			}
			else s.push(a[j]),use[a[j]]++;
		}
		while(!s.empty()) ans[s.top()]++,use[s.top()]--,s.pop();
	}
	for(int i=1;i<=m;i++) cout<<ans[i]<<" ";
	cout<<endl;
	return 0;
}
