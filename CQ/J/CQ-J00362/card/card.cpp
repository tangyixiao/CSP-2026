#include<bits/stdc++.h>
using namespace std;
const int N=5e5+5;
const int M=3e5+5;
int n,m,a[N],b[N],ans[M];
void del(int l,int r) {
	for (int i=l;i<=r;i++) {
		b[i]=-1;
	} 
}
int main() {
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	cin >> n >> m;
	for (int i=1;i<=n;i++) {
		cin >> a[i];
	}
	for (int i=0;i<n;i++) {
		for (int j=i+1;j<=n;j++) {
			b[j]=a[j];
		}
		for (int j=i+1;j<=n;j++) {
			for (int k=i+1;k<j;k++) {
				if (b[j]==b[k]&&b[j]!=-1) {
					del(k,j-1);
				}
			}
		}
		for (int j=i+1;j<=n;j++) {
			if (b[j]!=-1) {
				ans[b[j]]++;
			}
		}
	} 
	for (int i=1;i<=m;i++) {
		cout << ans[i] << " ";
	}
	return 0;
}
