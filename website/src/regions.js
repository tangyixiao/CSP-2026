/** Return a decorative, self-contained SVG, or nothing for an unknown region. */
export function regionArtwork(code) {
  if (typeof code !== 'string' || !/^[A-Z]{2}$/.test(code) || !Object.hasOwn(artwork, code)) return '';
  const paths = artwork[code].paths.map(d => `<path d="${d}"/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 240" aria-hidden="true" focusable="false" data-region="${code}"><g fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" opacity=".62">${paths}</g></svg>`;
}
