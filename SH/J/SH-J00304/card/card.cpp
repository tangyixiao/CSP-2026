#include <iostream>
#include <stack>

using namespace std;

stack<int> s;
int n, m, a[500005], ans[300005], inc[300005];

int main(){
	freopen("card.in", "r", stdin);
	freopen("card.out", "w", stdout);
	cin >> n >> m;
	for(int i = 1;i <= n;i++){
		cin >> a[i];
	}
	for(int i = 1;i <= n;i++){
	//	cout << i << ": " << endl;
		for(int j = i;j <= n;j++){
			if(inc[a[j]]){
				while((s.size() && s.top() != a[j])){
					inc[s.top()]--;
					s.pop();
				}
		//		cout <<"pop ";
			}else{
		//		cout << "push ";
				s.push(a[j]);
				inc[a[j]]++;
			}	
		}
		while(s.size()){
			ans[s.top()]++;
			inc[s.top()]--;
		//	cout << s.top() << " ";
			s.pop();
		}
	//	cout << endl;
	}
	for(int i = 1;i <= m;i++){
		cout << ans[i] << " ";
	}
	return 0;
} 

