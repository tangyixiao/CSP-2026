#include<bits/stdc++.h>

using namespace std;
const int N=5e5+10;
int n,m;
int a[N];
vector<int> c[N];
int ans[N];
int ls[N],p[N];
int ld[N];
void sol(){
	cin>>n>>m;
	for(int i=1;i<=n;i++){
		cin>>a[i];
		c[a[i]].push_back(i);
	}
	for(int i=n;i>=1;i--){
		if(p[a[i]]==0) p[a[i]]=i;
		else ls[i]=p[a[i]];
	}
	for(int i=1;i<=n;i++) ld[i]=1;
	for(int i=2;i<=n;i++){
		if(ls[i-1]==0&&a[i-1]!=a[i]) ld[i]+=ld[i-1];
		if(ls[i]==0){
			for(auto v:c[a[i]]){
				if(v!=i)
				ld[i]+=ld[v];
			}
		}
		if(ls[i]==0) ans[a[i]]+=ld[i];
	}
	for(int i=1;i<=m;i++){
		cout<<ans[i]<<' ';
	}
	return ;
}
int main(){
	freopen("card.in","r",stdin);
	freopen("card.out","w",stdout);
	int t=1;
	while(t--) sol();
	return 0;
}
